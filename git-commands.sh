# Комит команды
git add .                                           # Сделать индексацию
git commit                                          # Сделать комит
git push                                            # Отправить изменения в репозиторий
git pull                                            # Слить изменения

# Команды веток
git branch -m old-branch new-branch                 # Создать ветку
git switch                                          # Переключить ветку